# push_to_github.sh — no longer needed

The repository has been pushed to GitHub. This script is kept only as a
reference for how to push from a fresh clone.

Repository: https://github.com/3aghous94-debug/nrp-solver

To clone and push updates in the future:

    git clone https://github.com/3aghous94-debug/nrp-solver.git
    cd nrp-solver
    # make changes
    git add -A && git commit -m "your message"
    git push origin main

You will be prompted for GitHub credentials on push. Configure a credential
helper or SSH key to avoid entering credentials each time:

    https://docs.github.com/en/get-started/getting-started-with-git/set-up-git
